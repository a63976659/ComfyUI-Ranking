/**
 * 获取翻译文案
 * @param {string} key - 文案键
 * @param {Object} params - 插值参数
 * @returns {string}
 */
export function t(key, params = {}) {
    const lang = translations[currentLang] || translations['zh-CN'];
    // 🔧 修复：原实现 lang[key] || zh[key] || key 会把「刻意留空的词条」当成缺失又退回中文。
    // 中文量词/助词在英文里没有对应，必须留空：
    //   chat.date_day        9月8日  → 9/8
    //   chat.chatting_suffix 与 X 聊天 → Chatting with X
    //   creator.output.unit  产出插件 12 个 → Plugins: 12
    //   profile.transactions_unit  5笔 → 5
    // 旧逻辑下英文界面实际显示为 9/8日、Chatting with X 聊天、Plugins: 12 个、(5笔)。
    // 现改为：词条存在即采用（含空串），仅在真正缺键时才回退到中文。
    let text = Object.prototype.hasOwnProperty.call(lang, key)
        ? lang[key]
        : (translations['zh-CN'][key] || key);
    
    // 处理插值 {name}
    Object.entries(params).forEach(([k, v]) => {
        text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
    });
    
    return text;
}

/**
 * 🔍 仅在词条存在时翻译，否则返回 fallback
 * （t() 缺失键时返回键名本身，不适合分类/标签等用户自定义内容的双语显示）
 */
export function tIfExists(key, fallback = '') {
    const lang = translations[currentLang] || translations['zh-CN'];
    // 🔧 与 t() 同口径：词条存在即采用（含刻意留空），仅在两级都缺键时用 fallback
    if (Object.prototype.hasOwnProperty.call(lang, key)) return lang[key];
    if (Object.prototype.hasOwnProperty.call(translations['zh-CN'], key)) return translations['zh-CN'][key];
    return fallback;
}

/**
 * 设置当前语言
 * @param {string} lang - 语言代码 ('zh-CN' | 'en-US')
 */
export function setLanguage(lang) {
    if (typeof lang === 'string' && Object.hasOwn(translations, lang)) {
        currentLang = lang;
        pendingLanguage = lang;
        try {
            localStorage.setItem('comfy_ranking_lang', lang);
            pendingLanguage = null;
        } catch {}
        
        // 触发语言变更事件
        document.dispatchEvent(new CustomEvent('comfy-language-change', { 
            detail: { lang } 
        }));
    }
}

/**
 * 获取当前语言
 * @returns {string}
 */
export function getLanguage() {
    return currentLang;
}

/**
 * 初始化 i18n
 */
export function initI18n() {
    if (pendingLanguage !== null) {
        currentLang = pendingLanguage;
        return;
    }
    // 🔧 修复：优先从全局设置读取语言
    try {
        const globalSettings = JSON.parse(localStorage.getItem('ComfyCommunity_Settings') || '{}');
        if (typeof globalSettings.language === 'string' && Object.hasOwn(translations, globalSettings.language)) {
            currentLang = globalSettings.language;
            return;
        }
    } catch (e) {}
    
    // 回退：从旧的独立存储读取
    let savedLang = null;
    try { savedLang = localStorage.getItem('comfy_ranking_lang'); }
    catch {}
    if (typeof savedLang === 'string' && Object.hasOwn(translations, savedLang)) {
        currentLang = savedLang;
    } else {
        // 检测浏览器语言
        const browserLang = navigator.language;
        if (browserLang.startsWith('en')) {
            currentLang = 'en-US';
        } else {
            currentLang = 'zh-CN';
        }
    }
}

/**
 * 添加自定义翻译
 * @param {string} lang - 语言代码
 * @param {Object} texts - 翻译文案对象
 */
export function addTranslations(lang, texts) {
    if (!translations[lang]) {
        translations[lang] = {};
    }
    Object.assign(translations[lang], texts);
}
